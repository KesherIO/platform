/**
 * Pre-build script: generates environment.sentry.ts from the NG_APP_SENTRY_DSN
 * environment variable. This file is imported by environment.production.ts and
 * gitignored — the DSN never appears in committed source.
 *
 * Usage: node apps/frontend/scripts/write-sentry-env.js
 * Called automatically before `nx build frontend` via the Vercel build command.
 */
const fs = require('fs');
const path = require('path');

const dsn = process.env.NG_APP_SENTRY_DSN || '';
const release = process.env.VERCEL_GIT_COMMIT_SHA || '';

const content = `// AUTO-GENERATED by scripts/write-sentry-env.js — do not edit or commit
export const sentryConfig = {
  dsn: '${dsn.replace(/'/g, "\\'")}',
  release: '${release.replace(/'/g, "\\'")}',
};
`;

const outPath = path.join(
  __dirname,
  '..',
  'src',
  'environments',
  'environment.sentry.ts',
);

fs.writeFileSync(outPath, content, 'utf-8');
console.log(`[write-sentry-env] Wrote ${outPath} (DSN ${dsn ? 'set' : 'empty'})`);
